"""High-resolution desk texture for the splat configuration's wrist view (SO101_SPLAT=1).

The desk-top quad (calib/export_splat.py -> assets/splat/desk_top.usda) is textured with assets/real2sim/desk_albedo.png,
which build_real2sim_assets.py made from the OVERHEAD camera (~1.35 mm per camera pixel, stored at 0.5 mm/px). The wrist
camera sees the desk from ~10 cm (~0.2 mm/px), where that texture is a blurry, streaky magnification of the wood grain.
This writes an upsampled copy (x``--scale``) with fine synthetic wood detail -- long thin grain lines along the texture's
own grain direction (measured: the stripes run along image rows) plus small isotropic pores -- applied as a
multiplicative luminance modulation, so the colour and the low-frequency look (what the overhead camera matches) are
unchanged: a 2x2-pixel box filter of the result reproduces the source to ~3 grey levels (mean |err| 2.7, p99 13.5 with
the defaults; the long grain lines survive the box filter), well inside the desk-texture brightness DR (x0.75..1.25).

Writes <real2sim>/desk_albedo_hr.png and <splat>/desk_top_hr.usda (= desk_top.usda pointing at the new texture, same UVs;
the alternatives of mdp.randomize_desk_texture still resolve next to it). env_cfg prefers desk_top_hr.usda when present.

  ~/lr/bin/python scripts/build_desk_hr.py            # any python with numpy + opencv
"""
import argparse
import os

import cv2
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--real2sim", default="/mnt/secondary/so101_r2s/assets/real2sim")
ap.add_argument("--splat", default="/mnt/secondary/so101_r2s/assets/splat")
ap.add_argument("--scale", type=int, default=2)
ap.add_argument("--grain", type=float, default=0.05, help="relative amplitude of the grain lines")
ap.add_argument("--grain_len", type=float, default=30.0, help="grain correlation length along the grain [output px]")
ap.add_argument("--grain_width", type=float, default=1.2, help="grain line width (Gaussian sigma) [output px]")
ap.add_argument("--pores", type=float, default=0.035, help="relative amplitude of the isotropic fine detail")
ap.add_argument("--pore_size", type=float, default=0.8, help="pore blur sigma [output px]")
ap.add_argument("--seed", type=int, default=0)
args = ap.parse_args()

src = cv2.imread(os.path.join(args.real2sim, "desk_albedo.png"), cv2.IMREAD_UNCHANGED)
h, w = src.shape[:2]
g = src[..., :3].astype(np.float32).mean(2)
dx, dy = np.abs(np.diff(g, axis=1)).mean(), np.abs(np.diff(g, axis=0)).mean()
along_rows = dy > dx  # stripes run along the rows when the row-to-row change dominates
print(f"[desk_hr] {w}x{h} source; mean |d/dx| {dx:.2f} |d/dy| {dy:.2f} -> grain along {'rows' if along_rows else 'columns'}")

H, W = h * args.scale, w * args.scale
up = cv2.resize(src[..., :3], (W, H), interpolation=cv2.INTER_CUBIC).astype(np.float32)
rng = np.random.default_rng(args.seed)


def unit(x):
    return (x - x.mean()) / (x.std() + 1e-8)


sx, sy = (args.grain_len, args.grain_width) if along_rows else (args.grain_width, args.grain_len)
grain = unit(cv2.GaussianBlur(rng.standard_normal((H, W), dtype=np.float32), (0, 0), sigmaX=sx, sigmaY=sy))
pores = unit(cv2.GaussianBlur(rng.standard_normal((H, W), dtype=np.float32), (0, 0), args.pore_size))
mod = 1.0 + args.grain * grain + args.pores * pores
out = np.clip(up * mod[..., None], 0, 255)
# keep the low-pass (what the overhead camera sees) equal to the source
low = cv2.resize(out, (w, h), interpolation=cv2.INTER_AREA)
err = np.abs(low - src[..., :3].astype(np.float32))
print(f"[desk_hr] {W}x{H}; low-pass vs source |err| mean {err.mean():.2f} p99 {np.percentile(err, 99):.2f}")
dst = os.path.join(args.real2sim, "desk_albedo_hr.png")
cv2.imwrite(dst, out.round().astype(np.uint8), [cv2.IMWRITE_PNG_COMPRESSION, 6])
print(f"[desk_hr] wrote {dst} ({os.path.getsize(dst) / 1e6:.1f} MB)")

usd = open(os.path.join(args.splat, "desk_top.usda")).read()
assert "desk_albedo.png@" in usd, "desk_top.usda does not reference desk_albedo.png"
usd = usd.replace("desk_albedo.png@", "desk_albedo_hr.png@").replace(
    "Generated by calib/export_splat.py", "Generated by calib/export_splat.py; texture swapped by scripts/build_desk_hr.py")
dst_usd = os.path.join(args.splat, "desk_top_hr.usda")
open(dst_usd, "w").write(usd)
print(f"[desk_hr] wrote {dst_usd}")
